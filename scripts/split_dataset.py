"""
Build a reproducible SUBJECT-LEVEL train/val/test split and verify it is
leak-free.

The rationale for subject-level splitting (and why the original filename
"train"/"val" tags are not trusted) is documented in src/splitting.py and in
the README section "Why subject-level splitting".

Outputs:
    data/splits.json            the split itself
    outputs/metrics/split_report.md   human-readable summary + leakage check

Usage:
    python scripts/split_dataset.py
    python scripts/split_dataset.py --seed 7 --out data/splits_seed7.json
"""
import os
import sys
import json
import argparse

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from src.config import load_config, resolve_path
from src.splitting import build_split, verify_no_leakage, parse_subject
from src.utils import set_seed, ensure_dir
from src.preprocessing import load_mask


def empty_mask_counts(files, masks_dir):
    """Count empty masks per split — measured, not assumed. None if masks absent."""
    if not os.path.isdir(masks_dir):
        return None
    n_empty = 0
    for f in files:
        p = os.path.join(masks_dir, f)
        if os.path.exists(p) and load_mask(p).sum() == 0:
            n_empty += 1
    return n_empty


def main():
    parser = argparse.ArgumentParser(description="Build a leak-free dataset split.")
    parser.add_argument("--config", default=None)
    parser.add_argument("--out", default=None)
    parser.add_argument("--seed", type=int, default=None, help="Override config seed")
    parser.add_argument("--skip-mask-stats", action="store_true",
                        help="Skip reading every mask to count empty masks per split")
    args = parser.parse_args()

    cfg = load_config(args.config)
    seed = args.seed if args.seed is not None else cfg.seed
    set_seed(seed)

    images_dir = resolve_path(cfg.data.images_dir)
    if not os.path.isdir(images_dir):
        print(f"Images directory not found: {images_dir}\n"
              f"See DATASET_SETUP.md for where to place the dataset.")
        sys.exit(1)

    split = build_split(
        images_dir,
        val_fraction=cfg.data.val_fraction,
        test_fraction=cfg.data.test_fraction,
        seed=seed,
        split_level=cfg.data.get("split_level", "subject"),
    )

    out_path = args.out or resolve_path("data/splits.json")
    ensure_dir(os.path.dirname(out_path))
    with open(out_path, "w") as f:
        json.dump(split, f, indent=2)

    summary = verify_no_leakage(split)

    print(f"Split level: {split['split_level']}   seed: {seed}")
    print(f"Subjects: total={split['n_total_subjects']} "
          f"train={summary['subjects']['train']} val={summary['subjects']['val']} "
          f"test={summary['subjects']['test']}")
    print(f"Images:   train={summary['images']['train']} "
          f"val={summary['images']['val']} test={summary['images']['test']}")
    print(f"Unmatched filenames (excluded from split): {split['n_unmatched_filenames']}")
    print("Leakage check PASSED: no subject and no file appears in more than one split.")
    print(f"Wrote split file to {out_path}")

    # ---- report -------------------------------------------------------------
    masks_dir = resolve_path(cfg.data.masks_dir)
    empties = {}
    if not args.skip_mask_stats:
        for name in ("train", "val", "test"):
            empties[name] = empty_mask_counts(split[f"{name}_files"], masks_dir)

    L = ["# Dataset Split Report", "",
         "Generated by `scripts/split_dataset.py`. Every number is measured from "
         "the files on disk.", "",
         f"- Split level: **{split['split_level']}**",
         f"- Random seed: **{seed}** (the split is fully reproducible from this seed)",
         f"- Total subjects: **{split['n_total_subjects']}**",
         f"- Filenames with no parsable subject ID: {split['n_unmatched_filenames']}",
         "", "## Split sizes", "",
         "| Split | Subjects | Images | Empty masks |", "|---|---|---|---|"]
    for name in ("train", "val", "test"):
        e = empties.get(name)
        L.append(f"| {name} | {summary['subjects'][name]} | {summary['images'][name]} | "
                 f"{e if e is not None else 'not measured'} |")

    L += ["", "## Leakage verification", "",
          "`src.splitting.verify_no_leakage` ran three independent checks and all "
          "passed:", "",
          "1. No subject ID appears in more than one split.",
          "2. No image filename appears in more than one split.",
          "3. Every file's parsed subject ID belongs to its own split's subject list.",
          "",
          "This check also runs as an automated test "
          "(`tests/test_splitting.py::test_committed_split_is_leak_free`), so a "
          "leaked split fails the test suite rather than silently inflating results.",
          "", "## Subject IDs per split", "",
          f"- **train** ({len(split['train_subjects'])}): {', '.join(split['train_subjects'])}",
          f"- **val** ({len(split['val_subjects'])}): {', '.join(split['val_subjects'])}",
          f"- **test** ({len(split['test_subjects'])}): {', '.join(split['test_subjects'])}",
          ""]

    report_path = resolve_path("outputs/metrics/split_report.md")
    ensure_dir(os.path.dirname(report_path))
    with open(report_path, "w") as f:
        f.write("\n".join(L))
    print(f"Wrote split report to {report_path}")


if __name__ == "__main__":
    main()
